@pytest.mark.parametrize("case_id", CASE_IDS)
def test_corpus_is_reproducible_with_live_swisseph(case_id):
    """The on-disk reference must match a live swisseph evaluation (either backend)."""
    case = CASES[case_id]
    ref = case["reference"]
    utc = _civil(case).astimezone(timezone.utc)
    jd_ut = swe.julday(utc.year, utc.month, utc.day, utc.hour + utc.minute / 60 + utc.second / 3600)
    eot = swe.time_equ(jd_ut)
    eot_min = (eot[0] if isinstance(eot, tuple) else eot) * 1440.0
    assert math.isclose(eot_min, ref["equation_of_time_minutes"], abs_tol=1e-3)
    lon = case["input"]["longitude_deg"]
    lat = swe.lmt_to_lat(jd_ut + lon / 360.0, lon)
    lat = lat[0] if isinstance(lat, tuple) else lat
    _, _, _, h = swe.revjul(lat)
    assert _circular_hours_delta(h, ref["tlst_hours"]) < 1e-4


