@pytest.mark.parametrize("case_id", CASE_IDS)
def test_solar_time_leaf_matches_reference_when_offset_is_passed(case_id):
    case = CASES[case_id]
    ref = case["reference"]
    civil = _civil(case)
    civil_hours = civil.hour + civil.minute / 60 + civil.second / 3600
    tst = true_solar_time(
        civil_hours,
        case["input"]["longitude_deg"],
        civil.timetuple().tm_yday,
        timezone_offset_hours=ref["utc_offset_minutes"] / 60.0,
    )
    assert _circular_hours_delta(tst, ref["tlst_hours"]) < HOURS_TOL_APPROX, (case_id, tst, ref["tlst_hours"])


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_solar_time_leaf_without_offset_is_only_valid_for_utc_zones(case_id):
    """Documents the trap behind DEV-2026-008: omitting ``timezone_offset_hours``
    treats civil time as LMT. The result is right only when the zone offset is 0."""
    case = CASES[case_id]
    ref = case["reference"]
    civil = _civil(case)
    civil_hours = civil.hour + civil.minute / 60 + civil.second / 3600
    tst_no_offset = true_solar_time(civil_hours, case["input"]["longitude_deg"], civil.timetuple().tm_yday)
    delta = _circular_hours_delta(tst_no_offset, ref["tlst_hours"])
    # The no-offset variant is off by (zone_offset − longitude_correction): the
    # distance between the zone meridian and the birth meridian. For a
    # zone-offset-0 case this collapses to the longitude correction alone.
    expected_error_hours = abs(ref["utc_offset_minutes"] - ref["longitude_correction_minutes"]) / 60.0
    assert math.isclose(delta, expected_error_hours, abs_tol=HOURS_TOL_APPROX), (case_id, delta)


