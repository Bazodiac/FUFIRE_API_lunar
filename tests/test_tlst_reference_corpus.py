@pytest.mark.xfail(strict=True, reason=DEV_011)
def test_tlst_day_pillar_uses_tlst_date_before_solar_midnight(client):
    """Madrid 2024-02-22 00:30 CET has TLST 23:01 on 2024-02-21. With
    ``standard=TLST, boundary=midnight`` the day pillar must therefore be the
    2024-02-21 pillar (the one a CIVIL noon request on 02-21 yields)."""
    base = {"tz": "Europe/Madrid", "lon": -3.7038, "lat": 40.4168, "boundary": "midnight"}
    r_tlst = client.post("/calculate/bazi", json={**base, "date": "2024-02-22T00:30:00", "standard": "TLST"})
    r_prev = client.post("/calculate/bazi", json={**base, "date": "2024-02-21T12:00:00", "standard": "CIVIL"})
    if 503 in (r_tlst.status_code, r_prev.status_code):
        pytest.skip("ephemeris unavailable")
    assert r_tlst.status_code == 200 and r_prev.status_code == 200
    assert r_tlst.json()["pillars"]["day"] == r_prev.json()["pillars"]["day"], (
        r_tlst.json()["pillars"]["day"], r_prev.json()["pillars"]["day"]
    )
